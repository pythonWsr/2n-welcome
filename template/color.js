// template/color.js
//
// ═══════════════════════════════════════════════════════════════
//  用法
// ═══════════════════════════════════════════════════════════════
//
//   {{color|前景色|文本}}
//   {{color|前景色|背景色|文本}}
//
//   前景色 / 背景色   支持任意 CSS 颜色值：
//                     #rrggbb、#rgb、rgb(...)、hsl(...)、
//                     以及标准颜色名 red/blue 等。
//
//   文本              原样插入，不转义。因此可以包含 HTML 或已
//                     被 wikiParser 处理过的内联标记，如
//                     <strong>'''粗体'''</strong>、行内代码等。
//
// ═══════════════════════════════════════════════════════════════
//  示例
// ═══════════════════════════════════════════════════════════════
//
//   {{color|#2bffa3|血祭}}
//   {{color|#1fdbde|公会}}
//   {{color|#ffffff|#2563eb|白字蓝底}}
//   {{color|#555555|'''加粗的灰色文字'''}}
//
// ═══════════════════════════════════════════════════════════════
//  注意：内容中不能出现 | 与 }}
// ═══════════════════════════════════════════════════════════════
//
//   | 是模板参数分隔符；文本自身含 | 时会被切分。
//   连续两个右花括号会被 wikiParser 的模板匹配提前截断，
//   需要字面 }} 时，请使用 HTML 实体 &#125;&#125;。
//
// ═══════════════════════════════════════════════════════════════
//  实现说明
// ═══════════════════════════════════════════════════════════════
//
//   不转义文本，以便上层渲染好的 <strong> / <em> 标记能够生效。
//   如果你需要纯文本内容，请在调用前自行做 HTML 转义。

export default {
  name: 'color',
  isBlock: false,
  render(params) {
    if (params.length < 2) return '';
    const textColor = params[0];
    const text = params[params.length - 1];
    const bgColor = params.length > 2 ? params[1] : null;
    const style = `color:${textColor};${bgColor ? 'background-color:' + bgColor + ';' : ''}`;
    // 不再转义 text，允许内联标记（如 <strong>）
    return `<span style="${style}">${text}</span>`;
  }
};
